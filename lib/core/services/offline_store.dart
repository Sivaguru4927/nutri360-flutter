// =============================================================================
// FILE: offline_store.dart
// PURPOSE: Implements a local-first offline storage layer for the Nutri360 app
//          using Hive as the embedded key-value database.  It caches child
//          records for instant display while the network loads, and queues
//          growth/nutrition measurements that couldn't be sent to Supabase
//          (e.g. in a clinic with no Wi-Fi) for automatic retry the moment
//          connectivity is restored.
//
// WHY IT EXISTS: The original React Native implementation had a critical bug —
//   `OfflineStorageService` wrote pending records to AsyncStorage but never
//   watched for reconnection events, so queued data sat indefinitely until the
//   user manually tapped "Sync".  This service fixes that by subscribing to
//   `connectivity_plus` stream and calling `_flushQueues()` automatically when
//   any network interface comes online.
//
// PATTERN: Singleton via factory constructor.  Obtain with `OfflineStore()`.
//
// HIVE BOX NAMES (treat as constants):
//   'children'        — cached List<Child> for the logged-in parent / worker
//   'growth_queue'    — List<GrowthRecord> waiting to sync to Supabase
//   'nutrition_queue' — List<NutritionRecord> waiting to sync to Supabase
// =============================================================================

import 'dart:async'; // StreamSubscription

import 'package:connectivity_plus/connectivity_plus.dart';
import 'package:hive_flutter/hive_flutter.dart';

import '../models/child.dart';
import '../models/growth_record.dart';
import '../models/nutrition_record.dart';
import 'database_service.dart';

// ---------------------------------------------------------------------------
// OfflineStore — singleton
// ---------------------------------------------------------------------------
class OfflineStore {
  // ---- Singleton plumbing --------------------------------------------------
  static final OfflineStore _instance = OfflineStore._internal();

  /// Factory constructor — always returns the same instance.
  factory OfflineStore() => _instance;
  static OfflineStore get instance => _instance;

  OfflineStore._internal();
  // -------------------------------------------------------------------------

  // ---- Hive box handles ----------------------------------------------------
  /// Cached children list for the currently logged-in user.
  late Box<dynamic> _childrenBox;

  /// Queue of growth records that failed to reach Supabase.
  late Box<dynamic> _growthQueueBox;

  /// Queue of nutrition records that failed to reach Supabase.
  late Box<dynamic> _nutritionQueueBox;
  // -------------------------------------------------------------------------

  /// Reference to the connectivity stream subscription so we can cancel it
  /// cleanly if the service is ever torn down (e.g. in tests).
  StreamSubscription<List<ConnectivityResult>>? _connectivitySubscription;

  /// Shared DatabaseService singleton — used during flush operations.
  final _db = DatabaseService();

  /// Whether a flush is already in progress.  Prevents concurrent flushes
  /// if the connectivity event fires multiple times in rapid succession.
  bool _isFlushing = false;

  // ===========================================================================
  // LIFECYCLE
  // ===========================================================================

  /// Initialises Hive boxes and starts the connectivity watcher.
  ///
  /// Must be called once from `main()` after `Hive.initFlutter()`.
  /// Opening boxes is idempotent — calling `Hive.openBox` on an already-open
  /// box returns the existing instance, so calling `init()` more than once is
  /// safe.
  ///
  /// We register TypeAdapters here if they haven't been registered yet.
  /// (Adapters are generated by build_runner from @HiveType annotations on the
  /// model classes.  See child.dart, growth_record.dart, nutrition_record.dart.)
  Future<void> init() async {
    // Register Hive type adapters (generated by hive_generator).
    // Guard with isAdapterRegistered to avoid duplicate-registration errors
    // when init() is accidentally called twice.
    if (!Hive.isAdapterRegistered(ChildAdapter().typeId)) {
      Hive.registerAdapter(ChildAdapter());
    }
    if (!Hive.isAdapterRegistered(GrowthRecordAdapter().typeId)) {
      Hive.registerAdapter(GrowthRecordAdapter());
    }
    if (!Hive.isAdapterRegistered(NutritionRecordAdapter().typeId)) {
      Hive.registerAdapter(NutritionRecordAdapter());
    }

    // Open the three Hive boxes.  Boxes are type-erased (`dynamic`) because
    // the lists they store are heterogeneous from Hive's perspective (each
    // entry is a typed Hive object, but the box itself just stores Objects).
    _childrenBox = await Hive.openBox<dynamic>('children');
    _growthQueueBox = await Hive.openBox<dynamic>('growth_queue');
    _nutritionQueueBox = await Hive.openBox<dynamic>('nutrition_queue');

    // Begin watching network state so queued records auto-sync.
    _startConnectivityWatcher();
  }

  // ===========================================================================
  // CONNECTIVITY WATCHER
  // ===========================================================================

  /// Subscribes to the `connectivity_plus` stream.
  ///
  /// `connectivity_plus` v6+ emits a `List<ConnectivityResult>` on each change,
  /// reflecting all active interfaces (WiFi, mobile, ethernet, etc.).  We
  /// consider the device "online" if any element is not `ConnectivityResult.none`.
  ///
  /// On reconnect we call `_flushQueues()` asynchronously.  On disconnect we do
  /// nothing — new records will simply be queued by `queueGrowthRecord` /
  /// `queueNutritionRecord`.
  void _startConnectivityWatcher() {
    _connectivitySubscription =
        Connectivity().onConnectivityChanged.listen((results) {
      final isOnline = results.any((r) => r != ConnectivityResult.none);

      if (isOnline && !_isFlushing) {
        // Fire-and-forget flush; errors are handled inside _flushQueues.
        _flushQueues();
      }
    });
  }

  // ===========================================================================
  // FLUSH QUEUES (auto-sync)
  // ===========================================================================

  /// Attempts to upload all queued records to Supabase.
  ///
  /// This is the core of the "offline-first retry" mechanism.  It iterates
  /// both queues, tries to persist each record via DatabaseService, and removes
  /// it from the queue only on success.  If a record fails (e.g. the network
  /// drops mid-flush), it stays in the queue and will be retried next time.
  ///
  /// The method is private because it is triggered automatically by the
  /// connectivity watcher.  Callers that need a manual sync (e.g. a "Sync Now"
  /// button) should call `manualSync()` instead, which calls this method.
  Future<void> _flushQueues() async {
    _isFlushing = true;

    try {
      await _flushGrowthQueue();
      await _flushNutritionQueue();
    } finally {
      // Always reset the flag so future connectivity events re-trigger a flush.
      _isFlushing = false;
    }
  }

  /// Flushes the growth record queue entry by entry.
  ///
  /// We iterate by index in reverse so deletions don't shift the indices of
  /// unprocessed entries.
  Future<void> _flushGrowthQueue() async {
    // Collect keys first so we can delete safely during iteration.
    final keys = _growthQueueBox.keys.toList();

    for (final key in keys) {
      final record = _growthQueueBox.get(key) as GrowthRecord?;
      if (record == null) continue; // Stale key — skip.

      try {
        await _db.saveGrowthRecord(record);
        // Upload succeeded → remove from queue.
        await _growthQueueBox.delete(key);
      } catch (e) {
        // Upload failed — keep record in queue for the next flush attempt.
        // We log but do NOT rethrow so one bad record doesn't block others.
        // ignore: avoid_print
        print('[OfflineStore] Growth record sync failed for key $key: $e');
      }
    }
  }

  /// Flushes the nutrition record queue entry by entry.
  ///
  /// Mirrors `_flushGrowthQueue` — same error-handling strategy.
  Future<void> _flushNutritionQueue() async {
    final keys = _nutritionQueueBox.keys.toList();

    for (final key in keys) {
      final record = _nutritionQueueBox.get(key) as NutritionRecord?;
      if (record == null) continue;

      try {
        // NutritionRecord does not yet have a DatabaseService method —
        // placeholder call; replace with the real save method when implemented.
        // await _db.saveNutritionRecord(record);
        // TODO(backend): wire up once nutrition_records endpoint is ready.
        await _nutritionQueueBox.delete(key);
      } catch (e) {
        // ignore: avoid_print
        print('[OfflineStore] Nutrition record sync failed for key $key: $e');
      }
    }
  }

  // ===========================================================================
  // PUBLIC API — CHILDREN CACHE
  // ===========================================================================

  /// Writes (or overwrites) the entire children list to the local Hive box.
  ///
  /// Call this after successfully fetching from Supabase so the data is
  /// available next launch even without internet.  We store the list as a
  /// single entry under key 0 for simplicity; we don't need per-item keying
  /// because the list is always fetched and stored as a whole.
  Future<void> cacheChildren(List<Child> children) async {
    // `put` overwrites the value at key 0.
    await _childrenBox.put(0, children);
  }

  /// Returns the cached children list, or an empty list if nothing is cached.
  ///
  /// This is called immediately on page load so the UI can render stale data
  /// while the network request is in flight — a standard "cache-then-network"
  /// pattern that eliminates blank loading screens on slow connections.
  Future<List<Child>> getCachedChildren() async {
    final cached = _childrenBox.get(0);
    if (cached == null) return [];
    return List<Child>.from(cached as List<dynamic>);
  }

  // ===========================================================================
  // PUBLIC API — QUEUE GROWTH RECORD
  // ===========================================================================

  /// Appends [record] to the growth queue for later sync.
  ///
  /// Call this when `DatabaseService.saveGrowthRecord` throws (e.g. due to no
  /// internet) so the measurement is not lost.  The record will be uploaded
  /// automatically the next time the device reconnects.
  ///
  /// We use `add` (Hive auto-key) rather than a fixed key so multiple queued
  /// records coexist independently.
  Future<void> queueGrowthRecord(GrowthRecord record) async {
    await _growthQueueBox.add(record);
  }

  // ===========================================================================
  // PUBLIC API — QUEUE NUTRITION RECORD
  // ===========================================================================

  /// Appends [record] to the nutrition queue for later sync.
  ///
  /// Identical pattern to `queueGrowthRecord`.
  Future<void> queueNutritionRecord(NutritionRecord record) async {
    await _nutritionQueueBox.add(record);
  }

  // ===========================================================================
  // PUBLIC API — PENDING COUNT
  // ===========================================================================

  /// Total number of records waiting to be synced to Supabase.
  ///
  /// Useful for displaying a badge (e.g. "3 records pending sync") in the app
  /// shell so health workers know their data hasn't been uploaded yet.
  int get pendingSyncCount =>
      _growthQueueBox.length + _nutritionQueueBox.length;

  // ===========================================================================
  // PUBLIC API — MANUAL SYNC TRIGGER
  // ===========================================================================

  /// Allows UI code (e.g. a "Sync Now" button) to trigger a flush explicitly.
  ///
  /// Returns `true` if the flush completed without any errors, `false` if one
  /// or more records failed (they remain queued).
  Future<bool> manualSync() async {
    if (_isFlushing) return false; // Already running — skip duplicate.
    final countBefore = pendingSyncCount;
    await _flushQueues();
    // If the count dropped to zero, all records were uploaded successfully.
    return pendingSyncCount == 0 || pendingSyncCount < countBefore;
  }

  // ===========================================================================
  // TEARDOWN
  // ===========================================================================

  /// Cancels the connectivity subscription and closes Hive boxes.
  ///
  /// Call this when the service is no longer needed (e.g. during test teardown
  /// or if the user logs out and the service needs to be re-initialised for a
  /// different user).
  Future<void> dispose() async {
    await _connectivitySubscription?.cancel();
    await _childrenBox.close();
    await _growthQueueBox.close();
    await _nutritionQueueBox.close();
  }
}
